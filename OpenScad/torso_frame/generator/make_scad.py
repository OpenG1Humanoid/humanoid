"""Write out/torso_frame/torso_frame.scad from layout.py (+ report.json for the screw list)."""
import json, os
import layout as L
from prims import WORK, TF
r = json.load(open(os.path.join(WORK, 'report.json')))
mem = ",\n    ".join(f'["{n}", [{", ".join(f"{v:g}" for v in b)}], "{a}"]' for n, b, a in L.members())
EXP = {'front_panel': (1, 0, 0), 'back_panel': (-1, 0, 0), 'top_panel': (0, 0, 1.4), 'shoulder_block_L': (0, 1, 1),
       'shoulder_block_R': (0, -1, 1), 'hatch_L': (0, 1.8, 1), 'hatch_R': (0, -1.8, 1), 'bottom_plate': (0, 0, -1),
       'compute_tray': (-0.4, 0, 0), 'driver_tray': (0.4, 0, 0)}
COL = {'front_panel': 'Gainsboro', 'back_panel': 'Silver', 'top_panel': 'WhiteSmoke', 'shoulder_block_L': 'DarkOrange',
       'shoulder_block_R': 'DarkOrange', 'hatch_L': 'Chocolate', 'hatch_R': 'Chocolate', 'bottom_plate': 'SteelBlue',
       'compute_tray': 'SeaGreen', 'driver_tray': 'Orchid'}
prt = ",\n    ".join(f'["{k}", "{COL[k]}", [{", ".join(f"{v:g}" for v in EXP[k])}]]' for k in EXP)
S = f'''// =====================================================================
//  torso_frame.scad - Open G1 torso on a 2020 aluminium frame (generated by generator/make_scad.py)
// =====================================================================
//  Units mm, torso_link frame (same as the G1 URDF / assembly.scad).
//  The printed parts are STLs in stl/ cut from the ORIGINAL torso_link_rev_1_0 outer surface
//  (generator/gen_torso.py); this file places them on the frame and draws the aluminium.
//
//  PART = "assembly" | "exploded" | "frame" | one printed part name (see PARTS)
//  Every printed part fits a 220 x 220 x 250 mm bed.
// =====================================================================
PART      = "assembly";
EXPLODE   = 70;        // mm, for "exploded"
SHOW_PANELS = true;    // front / back / top panels (hide to see inside)
SHOW_FRAME  = true;
SHOW_TRAYS  = true;
SHOW_BLOCKS = true;    // shoulder blocks + servo hatches

// ---------------- frame layout (from layout.py) ----------------
PROF = {L.PROF:g};
XF = {L.XF:g}; XB = {L.XB:g}; YP = {L.YP:g};
Z_PLATE = [{L.Z_PLATE[0]:g}, {L.Z_PLATE[1]:g}]; Z_TOPBAR = [{L.Z_TOPBAR[0]:g}, {L.Z_TOPBAR[1]:g}]; Z_LOWRAIL = [{L.Z_LOWRAIL[0]:g}, {L.Z_LOWRAIL[1]:g}];
// name, [x0, x1, y0, y1, z0, z1], long axis
MEMBERS = [
    {mem}
];
// printed part, colour, explode direction
PARTS = [
    {prt}
];

// ---------------- 2020 profile (slot 6) ----------------
module profile2020_2d() {{
    difference() {{
        offset(r = 1.5) offset(delta = -1.5) square(PROF, center = true);
        circle(d = 4.2, $fn = 24);                                  // core hole: tap M5 for end screws
        for (a = [0, 90, 180, 270]) rotate(a) {{
            translate([PROF/2 - 1.8, -3.1]) square([2, 6.2]);       // slot opening
            hull() {{                                                // T cavity
                translate([PROF/2 - 6.1, -2.5]) square([0.1, 5]);
                translate([PROF/2 - 1.8 - 0.1, -5.5]) square([0.1, 11]);
            }}
        }}
    }}
}}
module member(m) {{
    b = m[1]; ax = m[2];
    if (ax == "z") translate([(b[0]+b[1])/2, (b[2]+b[3])/2, b[4]]) linear_extrude(b[5]-b[4]) profile2020_2d();
    if (ax == "y") translate([(b[0]+b[1])/2, b[2], (b[4]+b[5])/2]) rotate([-90, 0, 0]) linear_extrude(b[3]-b[2]) profile2020_2d();
    if (ax == "x") translate([b[0], (b[2]+b[3])/2, (b[4]+b[5])/2]) rotate([0, 90, 0]) linear_extrude(b[1]-b[0]) profile2020_2d();
}}
module frame() for (m = MEMBERS) member(m);

// ---------------- printed parts ----------------
module printed(name) import(str("stl/", name, ".stl"), convexity = 10);
function shown(n) = (n == "front_panel" || n == "back_panel" || n == "top_panel") ? SHOW_PANELS
                  : (n == "compute_tray" || n == "driver_tray") ? SHOW_TRAYS
                  : (n == "shoulder_block_L" || n == "shoulder_block_R" || n == "hatch_L" || n == "hatch_R") ? SHOW_BLOCKS : true;

// whole torso, for assembly.scad (use <torso_frame/torso_frame.scad>)
module torso_framed(explode = 0) {{
    if (SHOW_FRAME) color("LightSteelBlue") frame();
    for (p = PARTS) if (shown(p[0])) color(p[1]) translate(explode * p[2]) printed(p[0]);
}}

if (PART == "assembly") torso_framed(0);
else if (PART == "exploded") torso_framed(EXPLODE);
else if (PART == "frame") color("LightSteelBlue") frame();
else printed(PART);
'''
cut = S.index('if (PART == "assembly")')
lib = S[:cut].replace('module printed(name) import(str("stl/", name, ".stl"), convexity = 10);',
    'torso_frame_stl_dir = "../../STL/torso_frame/";   // relative to the file you open\nmodule printed(name) import(str(torso_frame_stl_dir, name, ".stl"), convexity = 10);').replace('PART      = "assembly";\n', '')
open(os.path.join(os.path.dirname(TF), 'lib', 'torso_frame_lib.scad'), 'w').write(lib)
open(os.path.join(TF, 'torso_frame.scad'), 'w').write('include <../lib/torso_frame_lib.scad>\nPART = "assembly";\n\n' + S[cut:])
print(len(S.splitlines()), 'lines')
